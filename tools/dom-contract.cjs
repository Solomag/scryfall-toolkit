// Generates the DOM contract: every Scryfall class name the dark theme depends
// on, with what it is, which page it belongs to and which part of the theme
// reaches for it. When Scryfall renames one, this is the file to look in, and a
// test stops the stylesheet from quietly growing a dependency nobody wrote down.
const fs = require('node:fs');
const path = require('node:path');
// The project root, one folder up. These files used to sit in it.
const ROOT = path.join(__dirname, '..') + path.sep;

// The theme, read the way the browser reads it: the parts the manifest lists, in
// the order it lists them.
//
// The list comes from the manifest for the same reason the scripts below do. A
// part that is written and not listed is a part nothing checks; a part that is
// listed and not written is a page that loads no stylesheet at all. Reading a
// hard-coded file name instead is how this tool spent a while describing a
// stylesheet that no longer existed.
const manifest = JSON.parse(fs.readFileSync(ROOT + 'manifest.json', 'utf8'));
const themeGroup = (manifest.content_scripts || []).find(entry =>
  (entry.css || []).some(file => file.startsWith('src/styles/theme/')));
if (!themeGroup) {
  console.error('the manifest lists no src/styles/theme/ stylesheets');
  process.exit(1);
}
const THEME_PARTS = themeGroup.css.filter(file => file.startsWith('src/styles/theme/'));
for (const file of THEME_PARTS) {
  if (!fs.existsSync(ROOT + file)) {
    console.error('the manifest names ' + file + ' and it is not there');
    process.exit(1);
  }
}

// Which page family a rule belongs to is told by the page classes theme.js sets.
const FAMILIES = [
  ['stk-tagger', 'Tagger (tagger.scryfall.com), a separate app with its own classes'],
  ['stk-bots-page', 'The bots page (/bots), which Scryfall builds as marketing panels'],
  ['stk-blog-page', 'The blog (/blog), index and posts'],
  ['stk-team-page', 'The team page (/team), a purple marketing page'],
  ['stk-docs-page', 'The documentation pages (/docs, /bots) with their left menu'],
  ['stk-account-page', 'Signed-in pages: /settings, /profile, /decks, a user deck'],
  ['stk-deck', 'The deck editor (#deckbuilder) and deck lists'],
  ['general', 'Everywhere else: buttons, inputs, menus, card pages']
];

// Each rule is read out of the part it is written in, so the document can say
// where a dependency lives and not only how often it is reached for. Seven files
// named in a column is the answer to "which file do I open when Scryfall renames
// this" — the question the split was made to answer.
const rules = [];
const selectors = [];
for (const file of THEME_PARTS) {
  const css = fs.readFileSync(ROOT + file, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
  for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
    const sel = m[1].trim().replace(/\s+/g, ' ');
    if (!sel) continue;
    rules.push(sel);
    selectors.push({ sel, file, part: path.basename(file, '.css') });
  }
}

const byFamily = new Map(FAMILIES.map(([k]) => [k, new Map()]));
const partOf = new Map();
for (const { sel, part } of selectors) {
  let family = 'general';
  for (const [key] of FAMILIES) {
    if (key !== 'general' && sel.includes('.' + key)) { family = key; break; }
  }
  const classes = new Set();
  for (const m of sel.matchAll(/\.([a-zA-Z][a-zA-Z0-9_-]*)/g)) {
    if (m[1].startsWith('stk-')) continue; // our own markers, not Scryfall's
    classes.add(m[1]);
  }
  for (const cls of classes) {
    byFamily.get(family).set(cls, (byFamily.get(family).get(cls) || 0) + 1);
    if (!partOf.has(cls)) partOf.set(cls, new Set());
    partOf.get(cls).add(part);
  }
}

const out = [];
out.push('# Scryfall DOM contract');
out.push('');
out.push('Every Scryfall class name the dark theme depends on, and where it lives.');
out.push('');
out.push('**Why this file exists.** The theme paints over Scryfall\'s styles by naming their');
out.push('markup. That is a real dependency: Scryfall can rename a class at any time, and the');
out.push('symptom is a page that comes out partly unthemed. When that happens, this is the one');
out.push('place to look — not 358 rules scattered across a stylesheet.');
out.push('');
out.push('A test reads every part of the theme and fails if it uses a class name that is not listed');
out.push('here. Adding a rule that reaches for a new class means writing down what that class is.');
out.push('');
out.push('The **Part** column names the file a dependency is written in. That is the point of the');
out.push('split: one class name, one file to open, instead of a few hundred rules to search.');
out.push('');
out.push('Generated by `node tools/dom-contract.cjs`. Do not edit by hand.');
out.push('');
out.push('**Not included:** this project\'s own `stk-*` markers, which theme.js sets and which');
out.push('Scryfall knows nothing about.');
out.push('');
out.push('---');

let total = 0;
for (const [key, description] of FAMILIES) {
  const names = byFamily.get(key);
  if (!names || !names.size) continue;
  const sorted = [...names.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
  total += sorted.length;
  out.push('');
  out.push(`## ${description}`);
  out.push('');
  out.push('| Class | Rules reaching for it | Part |');
  out.push('| --- | --- | --- |');
  for (const [cls, count] of sorted) {
    const parts = [...partOf.get(cls)].sort();
    out.push(`| \`.${cls}\` | ${count} | ${parts.map(p => '`' + p + '`').join(', ')} |`);
  }
}

out.push('');
out.push('---');
out.push('');
out.push('## Selectors used from JavaScript');
out.push('');
out.push('The stylesheet is not the only thing that names Scryfall\'s markup. The scripts reach');
out.push('for it too, and those selectors are just as easy to break. They are listed here by the');
out.push('name itself, without the leading `.` or `#`.');
out.push('');
out.push('| Name | Kind | Used by |');
out.push('| --- | --- | --- |');

// The scripts to scan come from the manifest, not from a list written here.
//
// The list this replaced named content.js, and content.js was split into a core and
// nine feature files. The tool did not fail — a file that is not there is skipped —
// so it went on producing a document that described a card page which no longer
// existed, with none of the nine files that draw it. Reading the manifest means the
// contract cannot fall behind the extension again: a script that ships is a script
// that is scanned.
const SCRIPTS = [...new Set([
  ...(manifest.content_scripts || []).flatMap(entry => entry.js || []),
  ...(manifest.background ? [manifest.background.service_worker] : [])
])].filter(file => typeof file === 'string');
// Names this project invents are not Scryfall's to rename.
const OUR_PREFIXES = ['stk-', 'cleanup-improver__', 'modify-cleanup-', 'data-heading-'];
const isOurs = name => OUR_PREFIXES.some(prefix => name.replace(/^[.#[\]]+/, '').startsWith(prefix));
const jsNames = new Map();
for (const file of SCRIPTS) {
  const path = ROOT + file;
  if (!fs.existsSync(path)) {
    console.error('the manifest names ' + file + ' and it is not there');
    process.exitCode = 1;
    continue;
  }
  const js = fs.readFileSync(path, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
  const names = new Set();
  for (const m of js.matchAll(/querySelector(?:All)?\(\s*['"`]([^'"`]+)['"`]/g)) {
    for (const c of m[1].matchAll(/\.([a-zA-Z][a-zA-Z0-9_-]*)/g)) names.add('.' + c[1]);
    for (const c of m[1].matchAll(/#([a-zA-Z][a-zA-Z0-9_-]*)/g)) names.add('#' + c[1]);
    // Only data-* attributes carry meaning Scryfall chose; [class] and [href]
    // are HTML's, and nobody renames those.
    for (const c of m[1].matchAll(/\[(data-[a-z-]+)[=~|^$*]?=/g)) names.add('[' + c[1] + ']');
  }
  for (const m of js.matchAll(/getElementById\(\s*['"`]([a-zA-Z][a-zA-Z0-9_-]*)['"`]/g)) names.add('#' + m[1]);
  for (const name of names) {
    if (isOurs(name)) continue;
    if (!jsNames.has(name)) jsNames.set(name, new Set());
    jsNames.get(name).add(file);
  }
}
for (const [name, files] of [...jsNames.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  const kind = name.startsWith('.') ? 'class' : name.startsWith('#') ? 'id' : 'attribute';
  out.push(`| \`${name.slice(name.startsWith('[') ? 0 : 1)}\` | ${kind} | ${[...files].sort().join(', ')} |`);
}

out.push('');
out.push('---');
out.push('');
out.push(`Total: **${total}** Scryfall class names.`);
out.push('');

// Where to write. The test runs this and compares the result with what is
// committed, so it needs the output somewhere of its own — and it should not have
// to rewrite this file's source to get it, which is how a test ends up testing
// something other than the tool.
const OUT = process.env.STK_CONTRACT_OUT || (ROOT + 'docs/scryfall-dom.md');
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, out.join('\n') + '\n', 'utf8');
console.log(OUT + ' written');
console.log('families:', FAMILIES.filter(([k]) => byFamily.get(k).size).length);
console.log('class names:', total);
console.log('rules scanned:', rules.length);
