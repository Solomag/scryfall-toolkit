// Generates the DOM contract: every Scryfall class name theme.css depends on,
// with what it is and where it lives. When Scryfall renames one, this is the file
// to look in, and a test stops the stylesheet from quietly growing a dependency
// that nobody wrote down.
const fs = require('node:fs');
const ROOT = 'H:/Solo/Downloads/scryfall-toolkit/';
const css = fs.readFileSync(ROOT + 'theme.css', 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const bare = css.replace(/url\([^)]*\)/g, '').replace(/https?:\/\/[^\s"')]+/g, '');

// Which page family a rule belongs to is told by the page classes theme.js sets.
const FAMILIES = [
  ['stk-tagger', 'Tagger (tagger.scryfall.com), a separate app with its own classes'],
  ['stk-bots-page', 'The bots page (/bots), which Scryfall builds as marketing panels'],
  ['stk-blog-page', 'The blog (/blog), index and posts'],
  ['stk-team-page', 'The team page (/team), a purple marketing page'],
  ['stk-docs-page', 'The documentation pages (/docs, /bots) with their left menu'],
  ['stk-account-page', 'Signed-in pages: /settings, /profile, /decks, a user deck'],
  ['stk-deck', 'The deck editor (#deckbuilder) and deck lists'],
  ['general', 'Everywhere else: buttons, inputs, menus, card pages']
];

const rules = [];
for (const m of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) {
  const sel = m[1].trim().replace(/\s+/g, ' ');
  if (sel) rules.push(sel);
}

const byFamily = new Map(FAMILIES.map(([k]) => [k, new Map()]));
for (const sel of rules) {
  let family = 'general';
  for (const [key] of FAMILIES) {
    if (key !== 'general' && sel.includes('.' + key)) { family = key; break; }
  }
  const classes = new Set();
  for (const m of sel.matchAll(/\.([a-zA-Z][a-zA-Z0-9_-]*)/g)) {
    if (m[1].startsWith('stk-')) continue; // our own markers, not Scryfall's
    classes.add(m[1]);
  }
  for (const cls of classes) {
    byFamily.get(family).set(cls, (byFamily.get(family).get(cls) || 0) + 1);
  }
}

const out = [];
out.push('# Scryfall DOM contract');
out.push('');
out.push('Every Scryfall class name the dark theme depends on, and where it lives.');
out.push('');
out.push('**Why this file exists.** The theme paints over Scryfall\'s styles by naming their');
out.push('markup. That is a real dependency: Scryfall can rename a class at any time, and the');
out.push('symptom is a page that comes out partly unthemed. When that happens, this is the one');
out.push('place to look — not 358 rules scattered across a stylesheet.');
out.push('');
out.push('A test reads `theme.css` and fails if it uses a class name that is not listed here.');
out.push('Adding a rule that reaches for a new class means writing down what that class is.');
out.push('');
out.push('Generated by `node tools/dom-contract.cjs`. Do not edit by hand.');
out.push('');
out.push('**Not included:** this project\'s own `stk-*` markers, which theme.js sets and which');
out.push('Scryfall knows nothing about.');
out.push('');
out.push('---');

let total = 0;
for (const [key, description] of FAMILIES) {
  const names = byFamily.get(key);
  if (!names || !names.size) continue;
  const sorted = [...names.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
  total += sorted.length;
  out.push('');
  out.push(`## ${description}`);
  out.push('');
  out.push('| Class | Rules reaching for it |');
  out.push('| --- | --- |');
  for (const [cls, count] of sorted) out.push(`| \`.${cls}\` | ${count} |`);
}

out.push('');
out.push('---');
out.push('');
out.push('## Selectors used from JavaScript');
out.push('');
out.push('The stylesheet is not the only thing that names Scryfall\'s markup. The scripts reach');
out.push('for it too, and those selectors are just as easy to break. They are listed here by the');
out.push('name itself, without the leading `.` or `#`.');
out.push('');
out.push('| Name | Kind | Used by |');
out.push('| --- | --- | --- |');

const SCRIPTS = ['content.js', 'deck-clean-up.js', 'deck-edhrec.js', 'deck-search.js', 'deck-tools.js', 'deck-scryfall.js', 'theme.js'];
// Names this project invents are not Scryfall's to rename.
const OUR_PREFIXES = ['stk-', 'cleanup-improver__', 'modify-cleanup-', 'data-heading-'];
const isOurs = name => OUR_PREFIXES.some(prefix => name.replace(/^[.#[\]]+/, '').startsWith(prefix));
const jsNames = new Map();
for (const file of SCRIPTS) {
  const path = ROOT + file;
  if (!fs.existsSync(path)) continue;
  const js = fs.readFileSync(path, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/[^\n]*/g, '');
  const names = new Set();
  for (const m of js.matchAll(/querySelector(?:All)?\(\s*['"`]([^'"`]+)['"`]/g)) {
    for (const c of m[1].matchAll(/\.([a-zA-Z][a-zA-Z0-9_-]*)/g)) names.add('.' + c[1]);
    for (const c of m[1].matchAll(/#([a-zA-Z][a-zA-Z0-9_-]*)/g)) names.add('#' + c[1]);
    // Only data-* attributes carry meaning Scryfall chose; [class] and [href]
    // are HTML's, and nobody renames those.
    for (const c of m[1].matchAll(/\[(data-[a-z-]+)[=~|^$*]?=/g)) names.add('[' + c[1] + ']');
  }
  for (const m of js.matchAll(/getElementById\(\s*['"`]([a-zA-Z][a-zA-Z0-9_-]*)['"`]/g)) names.add('#' + m[1]);
  for (const name of names) {
    if (isOurs(name)) continue;
    if (!jsNames.has(name)) jsNames.set(name, new Set());
    jsNames.get(name).add(file);
  }
}
for (const [name, files] of [...jsNames.entries()].sort((a, b) => a[0].localeCompare(b[0]))) {
  const kind = name.startsWith('.') ? 'class' : name.startsWith('#') ? 'id' : 'attribute';
  out.push(`| \`${name.slice(name.startsWith('[') ? 0 : 1)}\` | ${kind} | ${[...files].sort().join(', ')} |`);
}

out.push('');
out.push('---');
out.push('');
out.push(`Total: **${total}** Scryfall class names.`);
out.push('');

fs.writeFileSync(ROOT + 'docs/scryfall-dom.md', out.join('\n') + '\n', 'utf8');
console.log('docs/scryfall-dom.md written');
console.log('families:', FAMILIES.filter(([k]) => byFamily.get(k).size).length);
console.log('class names:', total);
console.log('rules scanned:', rules.length);
